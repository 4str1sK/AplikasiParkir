    private void btnTambahActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnTambahActionPerformed
        int tarif = 0;

        //Validasi
        if (CBJenis.getSelectedIndex() == -1
        || TextTarif.getText().trim().isEmpty()
             
     ) {
            JOptionPane.showMessageDialog(this, "Isi Semua Data");
            return;
        }
        
         try {
            tarif = Integer.parseInt(TextTarif.getText().trim());
}        catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "Isi Data Tarif dengan Angka!");
            TextTarif.requestFocus();
        return;
}
        
        try {
            pst = conn.prepareStatement(
            "INSERT INTO tb_tarif (jenis_kendaraan, tarif_per_jam) VALUES (?,?)");
            
        pst.setString(1, CBJenis.getSelectedItem().toString());
        pst.setInt(2, tarif);

        pst.executeUpdate();

        JOptionPane.showMessageDialog(this, "Data berhasil ditambahkan");
        loadTable();
        clearForm();
        } catch (Exception e) {

    JOptionPane.showMessageDialog(this, e.getMessage());
}
        
        
        
        
        
    }//GEN-LAST:event_btnTambahActionPerformed

