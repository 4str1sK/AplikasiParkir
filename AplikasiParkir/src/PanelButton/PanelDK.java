    private void btnHapusActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnHapusActionPerformed
    int row = tblKendaraan.getSelectedRow();

    if (row == -1) {
    JOptionPane.showMessageDialog(this, "Pilih data dulu!");
    return;
}

//Delete via ID (Pusing banget coek, ga paham gwe, ngikutin tutorial dokumentasi :V)
    int id = Integer.parseInt(
    tblKendaraan.getValueAt(row, 0).toString()
);

    String plat = tblKendaraan.getValueAt(row, 1).toString();

        int confirm = JOptionPane.showConfirmDialog(
        this,
        "Yakin mau hapus kendaraan dengan plat " + plat + "?",
        "Konfirmasi",
    JOptionPane.YES_NO_OPTION
);

    if (confirm != JOptionPane.YES_OPTION) return;

    try {
        String sql = "DELETE FROM tb_kendaraan WHERE id_kendaraan = ?";
        PreparedStatement ps = conn.prepareStatement(sql);
        ps.setInt(1, id);

    int affected = ps.executeUpdate();

    if (affected > 0) {
        loadTable();
        JOptionPane.showMessageDialog(this, "Data berhasil dihapus");
    } else {
        JOptionPane.showMessageDialog(this, "Data gagal dihapus (tidak ditemukan)");
    }

    } catch (Exception e) {
        JOptionPane.showMessageDialog(this, e.getMessage());
}
    }//GEN-LAST:event_btnHapusActionPerformed

    private void btnTambahActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnTambahActionPerformed
        
    //Validasi
    if (TextPlat.getText().trim().isEmpty() 
    ||  CBJenis.getSelectedIndex() == -1
    ||  TextWarna.getText().trim().isEmpty()
    ||  TextPemilik.getText().trim().isEmpty()
) {
            
            
            
        JOptionPane.showMessageDialog(this, "Isi Semua Data");
        return;
    }

    try {
        pst = conn.prepareStatement(
            "INSERT INTO tb_kendaraan (plat_nomor, jenis_kendaraan, warna, pemilik, id_user) VALUES (?,?,?,?,?)"
        );

        pst.setString(1, TextPlat.getText());
        pst.setString(2, CBJenis.getSelectedItem().toString());
        pst.setString(3, TextWarna.getText());
        pst.setString(4, TextPemilik.getText());
        pst.setInt(5, Session.id_user);

        pst.executeUpdate();

        JOptionPane.showMessageDialog(this, "Data berhasil ditambahkan");
        loadTable();
        clearForm();

    } catch (Exception e) {
        JOptionPane.showMessageDialog(this, e.getMessage());
    }
    }//GEN-LAST:event_btnTambahActionPerformed

