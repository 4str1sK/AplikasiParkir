    private void loadTable() {
    DefaultTableModel model = new DefaultTableModel();
    model.addColumn("ID");
    model.addColumn("Nama Area");
    model.addColumn("Kapasitas Tersisa");
    model.addColumn("Terisi");
    model.addColumn("Kapasitas Maksimum");

    try {
        pst = conn.prepareStatement("SELECT * FROM tb_area_parkir");
        rs = pst.executeQuery();

        while (rs.next()) {
            int kapasitas = rs.getInt("kapasitas");
            int terisi = rs.getInt("terisi");
            int sisa = kapasitas - terisi;
            model.addRow(new Object[]{
                rs.getInt("id_area"), 
                rs.getString("nama_area"),
                sisa,
                terisi,
                kapasitas
            });
        }

        tblArea.setModel(model);


    } catch (Exception e) {
        JOptionPane.showMessageDialog(this, e.getMessage());
    }
}

