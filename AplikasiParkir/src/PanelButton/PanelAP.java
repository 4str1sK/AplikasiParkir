    private void btnTambahkanActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnTambahkanActionPerformed
        int kapasitas = 0;
        
        
        //ValidasI
        if (TextNama.getText().trim().isEmpty() 
        || TextKapasitas.getText().trim().isEmpty())
        { JOptionPane.showMessageDialog(this, "Isi Semua Data"); 
        return;
        }
   
        
        try {
            kapasitas = Integer.parseInt(TextKapasitas.getText().trim());
}        catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "Isi Data Kapasitas dengan Angka!");
            TextKapasitas.requestFocus();
        return;
}
        
        
        
        try {
        pst = conn.prepareStatement(
            "INSERT INTO tb_area_parkir (nama_area, kapasitas, terisi) VALUES (?,?,?)"
        );

        pst.setString(1, TextNama.getText());
        pst.setInt(2, kapasitas);
        pst.setInt(3, 0);
        pst.executeUpdate();

        JOptionPane.showMessageDialog(this, "Data berhasil ditambahkan");
        loadTable();
        clearForm();

    } catch (Exception e) {
        JOptionPane.showMessageDialog(this, e.getMessage());
    }
        clearForm();
                
      
    }//GEN-LAST:event_btnTambahkanActionPerformed

