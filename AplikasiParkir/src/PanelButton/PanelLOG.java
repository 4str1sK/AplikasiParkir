    private void loadTable() {
      DefaultTableModel model = new DefaultTableModel();
    model.addColumn("ID");
    model.addColumn("Nama");
    model.addColumn("Aktivitas");
    model.addColumn("Waktu");

    try {
        String sql = "SELECT l.id_log, u.nama_lengkap, l.aktivitas, l.waktu_aktivitas " +
                     "FROM tb_log_aktivitas l " +
                     "JOIN tb_user u ON l.id_user = u.id_user " +
                     "ORDER BY l.waktu_aktivitas DESC";

        pst = conn.prepareStatement(sql);
        rs = pst.executeQuery();

        while (rs.next()) {
            model.addRow(new Object[]{
                rs.getInt("id_log"),
                rs.getString("nama_lengkap"),
                rs.getString("aktivitas"),
                rs.getTimestamp("waktu_aktivitas")
            });
        }

        tblLog.setModel(model);

    } catch (Exception e) {
        JOptionPane.showMessageDialog(null, 
            "Gagal load data log: " + e.getMessage());
    }
}

