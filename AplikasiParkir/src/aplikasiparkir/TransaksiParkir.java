  private void loadCB() {
    try {
      String sql = "SELECT * FROM tb_area_parkir";
      PreparedStatement pst = conn.prepareStatement(sql);
      ResultSet rs = pst.executeQuery();

    while (rs.next()) {
        CBArea.addItem(new AreaItem(
            rs.getInt("id_area"),
            rs.getString("nama_area")
    ));
}
  } catch (Exception e) {
        JOptionPane.showMessageDialog(this, e.getMessage());
  }
  
  }
   
    
    
   private void loadTable() {

   
    DefaultTableModel model = new DefaultTableModel();
    model.addColumn("ID");
    model.addColumn("ID Kendaraan");
    model.addColumn("ID Area");
    model.addColumn("Status");

    try {

        String sql = "SELECT id_parkir, id_kendaraan, id_area, status FROM tb_transaksi";

        pst = conn.prepareStatement(sql);
        rs = pst.executeQuery();

        while (rs.next()) {

            model.addRow(new Object[]{
                rs.getInt("id_parkir"),
                rs.getInt("id_kendaraan"),
                rs.getInt("id_area"),
                rs.getString("status")
            });

        }

        tblPetugas.setModel(model);

    } catch (Exception e) {
        JOptionPane.showMessageDialog(this, e.getMessage());
    }
}

    
