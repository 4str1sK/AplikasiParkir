    private void btnMasukActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnMasukActionPerformed
    String plat = TextPlat.getText().trim();
    String jenis = CBJenis.getSelectedItem().toString();
    AreaItem selected = (AreaItem) CBArea.getSelectedItem();
    int idArea = selected.id;

if (plat.isEmpty() || idArea == -1) {
    JOptionPane.showMessageDialog(this, "Isi data dengan benar!");
    return;
}

try {
    conn.setAutoCommit(false);

    String cekSql = "SELECT id_kendaraan FROM tb_kendaraan WHERE plat_nomor = ?";
    pst = conn.prepareStatement(cekSql);
    pst.setString(1, plat);
    rs = pst.executeQuery();

    int idKendaraan;

    if (rs.next()) {
        idKendaraan = rs.getInt("id_kendaraan");
    } else {
        String insertKendaraan =
            "INSERT INTO tb_kendaraan (plat_nomor, jenis_kendaraan) VALUES (?, ?)";

        pst = conn.prepareStatement(insertKendaraan, Statement.RETURN_GENERATED_KEYS);
        pst.setString(1, plat);
        pst.setString(2, jenis);
        pst.executeUpdate();

        ResultSet gk = pst.getGeneratedKeys();
        gk.next();
        idKendaraan = gk.getInt(1);
    }
    
    String sqlTarif = "SELECT id_tarif FROM tb_tarif WHERE jenis_kendaraan = ?";
        PreparedStatement pstTarif = conn.prepareStatement(sqlTarif);
        pstTarif.setString(1, jenis);
        ResultSet rsTarif = pstTarif.executeQuery();

        int idTarif = -1;

        if (rsTarif.next()) {
            idTarif = rsTarif.getInt("id_tarif");
        } else {
            JOptionPane.showMessageDialog(this, "Tarif tidak ditemukan!");
            return;
        }
    
    String sql = "SELECT * FROM tb_area_parkir";
    PreparedStatement pst = conn.prepareStatement(sql);
    ResultSet rs = pst.executeQuery();

    while (rs.next()) {
        CBArea.addItem(new AreaItem(
            rs.getInt("id_area"),
            rs.getString("nama_area")
    ));
}

    String insertTransaksi =
        "INSERT INTO tb_transaksi (id_kendaraan, waktu_masuk, status, id_user, id_area, id_tarif) " +
        "VALUES (?, NOW(), 'masuk', ?, ?, ?)";

    pst = conn.prepareStatement(insertTransaksi);
    pst.setInt(1, idKendaraan);
    pst.setInt(2, Session.id_user);
    pst.setInt(3, idArea);
    pst.setInt(4,idTarif);

    pst.executeUpdate();

    conn.commit();

    JOptionPane.showMessageDialog(this, "Kendaraan berhasil masuk!");
    insertlog.tambahLog(Session.id_user, 
    "Memasukkan kendaraan :" + plat);
    loadTable();
    clearForm();

} catch (Exception e) {
    try { conn.rollback(); } catch (Exception ex) {}
    JOptionPane.showMessageDialog(this, e.getMessage());
}

    }//GEN-LAST:event_btnMasukActionPerformed

    private void btnKeluarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnKeluarActionPerformed
        String plat = TextPlat.getText().trim();
        int row = tblPetugas.getSelectedRow(); 
        if (row == -1) { JOptionPane.showMessageDialog(this, "Pilih data dulu!");
        return;
        } int idTransaksi = Integer.parseInt
        ( 
        tblPetugas.getValueAt(row, 0).toString() );

        
        try {

            String sqlAmbil = "SELECT waktu_masuk, id_tarif FROM tb_transaksi WHERE id_parkir = ?";
            PreparedStatement pstAmbil = conn.prepareStatement(sqlAmbil);
            pstAmbil.setInt(1, idTransaksi);
            ResultSet rs = pstAmbil.executeQuery();

            if (!rs.next()) {
                JOptionPane.showMessageDialog(this, "Data tidak ditemukan!");
                return;
            }

            Timestamp waktuMasuk = rs.getTimestamp("waktu_masuk");
            int idTarif = rs.getInt("id_tarif");

            Timestamp waktuKeluar = new Timestamp(System.currentTimeMillis());


            long selisihMillis = waktuKeluar.getTime() - waktuMasuk.getTime();
            double durasiJam = Math.ceil(selisihMillis / (1000.0 * 60 * 60));


            String sqlTarif = "SELECT tarif_per_jam FROM tb_tarif WHERE id_tarif = ?";
            PreparedStatement pstTarif = conn.prepareStatement(sqlTarif);
            pstTarif.setInt(1, idTarif);
            ResultSet rsTarif = pstTarif.executeQuery();

            if (!rsTarif.next()) {
                JOptionPane.showMessageDialog(this, "Tarif tidak ditemukan!");
                return;
            }

            double hargaPerJam = rsTarif.getDouble("tarif_per_jam");


            double totalBiaya = durasiJam * hargaPerJam;


            String sqlUpdate = "UPDATE tb_transaksi " +
                               "SET status = 'keluar', " +
                               "waktu_keluar = ?, " +
                               "durasi_jam = ?, " +
                               "biaya_total = ? " +
                               "WHERE id_parkir = ?";

            PreparedStatement pstUpdate = conn.prepareStatement(sqlUpdate);
            pstUpdate.setTimestamp(1, waktuKeluar);
            pstUpdate.setDouble(2, durasiJam);
            pstUpdate.setDouble(3, totalBiaya);
            pstUpdate.setInt(4, idTransaksi);

            pstUpdate.executeUpdate();

            JOptionPane.showMessageDialog(this,
                    "Kendaraan keluar!\nDurasi: " + durasiJam +
                    " jam\nTotal: Rp " + totalBiaya);
            
            insertlog.tambahLog(Session.id_user, 
            "Mengeluarkan kendaraan :" + plat + "dengan total biaya :" + totalBiaya + "dengan durasi jam" + durasiJam);
            loadTable();

} catch (Exception e) {
    JOptionPane.showMessageDialog(this, e.getMessage());
}

    }//GEN-LAST:event_btnKeluarActionPerformed

